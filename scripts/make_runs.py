"""Write runs/<model>-<decoding>-<benchmark>.sbatch: one frozen, self-contained job per Table 11 run, with every flag pinned.

    python scripts/make_runs.py

Each job runs from the repository root (``SLURM_SUBMIT_DIR``), reads models from ``CHECKPOINTS/posttrain`` (default ``checkpoints/posttrain``),
generates over a warm-up pass and seeds 0, 1 and 2, grades the run, and writes results/<model>-<decoding>/<benchmark>.json
and .score.json. The header is site-neutral: add partition, account or node selection on the sbatch command line. Jobs use
the environment as synced (``uv sync --extra eval``) rather than syncing it themselves, so concurrent jobs cannot race on it.
"""

from __future__ import annotations

from pathlib import Path

RUNS = Path(__file__).resolve().parent.parent / "runs"
BUDGETS = {"gsm8k": 512, "math500": 2048, "humaneval": 768, "ifeval": 1280}
PLMS = {"plm-1.3B-beta0.5": 10, "plm-1.3B-beta1": 10, "plm-1.3B-beta2": 10, "plm-3B-beta1": 7}   # model -> relaxed k
SCHEME_FOR_AR_BASELINE = "plm-1.3B-beta1"


def decodings() -> list[tuple[str, str, str]]:
    """(model, decoding, generate flags) for every Table 11 row."""
    rows = [("ar-1.3B", "ar-topk", "--ar --ar-sampler topk"),
            ("ar-1.3B", "ar-voronoi", f'--ar --ar-sampler voronoi --ar-voronoi-scheme "$CHECKPOINTS/posttrain/{SCHEME_FOR_AR_BASELINE}"')]
    for model, relaxed_k in PLMS.items():
        rows += [(model, "ar-topk", "--ar --ar-sampler topk"), (model, "ar-voronoi", "--ar --ar-sampler voronoi"),
                 (model, "exact", "--mode fast --match exact --k 7"), (model, "relaxed", f"--mode fast --match relaxed --k {relaxed_k}")]
    return rows


def sbatch(model: str, decoding: str, flags: str, benchmark: str) -> str:
    run = f"{model}-{decoding}"
    results = f"results/{run}/{benchmark}"
    return f"""#!/bin/bash
# Table 11: {model}, {decoding} decoding, {benchmark}. Warm-up pass, then seeds 0 1 2; graded at the end.
# Generated by scripts/make_runs.py; submit from the repository root.
#SBATCH --job-name=plm-{run}-{benchmark}
#SBATCH --time=06:00:00
#SBATCH --nodes=1
#SBATCH --ntasks-per-node=1
#SBATCH --cpus-per-task=8
#SBATCH --gres=gpu:1
#SBATCH --output=results/logs/%x-%j.log
#SBATCH --error=results/logs/%x-%j.log

set -euo pipefail
cd "${{SLURM_SUBMIT_DIR:-$PWD}}"
CHECKPOINTS=${{CHECKPOINTS:-checkpoints}}
export PYTHONPATH=third_party NLTK_DATA=third_party/nltk_data

[ -f prompts/{benchmark}/tasks.json ] || uv run --no-sync python -m plm.eval.build_prompts --benchmark {benchmark} --tokenizer "$CHECKPOINTS/posttrain/{SCHEME_FOR_AR_BASELINE}" --out-dir prompts/{benchmark}
mkdir -p results/{run}
uv run --no-sync python -m plm.generate --model "$CHECKPOINTS/posttrain/{model}" {flags} --dataset prompts/{benchmark}/prompts.json --tokens {BUDGETS[benchmark]} \\
    --max-model-len 4096 --stop-at-eos --seeds 0 1 2 --out {results}.json
uv run --no-sync python -m plm.eval.score --benchmark {benchmark} --results {results}.json --tasks prompts/{benchmark}/tasks.json
"""


def main() -> None:
    RUNS.mkdir(exist_ok=True)
    count = 0
    for model, decoding, flags in decodings():
        for benchmark in BUDGETS:
            (RUNS / f"{model}-{decoding}-{benchmark}.sbatch").write_text(sbatch(model, decoding, flags, benchmark))
            count += 1
    print(f"wrote {count} sbatches to {RUNS}")


if __name__ == "__main__":
    main()
